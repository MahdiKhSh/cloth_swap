export type Key = keyof typeof fa;
type Lang = "fa" | "en";

function initialLang(): Lang {
  try {
    return (localStorage.getItem("lang") as Lang) || "fa";
  } catch {
    return "fa";
  }
}

export const useLang = create<{ lang: Lang; toggle: () => void }>((set, get) => ({
  lang: initialLang(),
  toggle: () => {
    const lang = get().lang === "fa" ? "en" : "fa";
    try {
      localStorage.setItem("lang", lang);
    } catch {
      /* private mode */
    }
    set({ lang });
  },
}));

export function applyDir(lang: Lang) {
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "fa" ? "rtl" : "ltr";
}

export function useT() {
  const lang = useLang((s) => s.lang);
  const dict = lang === "fa" ? fa : en;
  return (key: Key, vars?: Record<string, string | number>) => {
    let s: string = dict[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
    return s;
  };
}

/** Job messages look like "tracking:12/81" or "sampling:1/1:3/8". */
export function jobMessage(t: ReturnType<typeof useT>, message: string) {
  if (!message) return "";
  const [key, ...parts] = message.split(":");
  const nums = parts.flatMap((p) => p.split("/"));
  const vars = { a: nums[0] ?? "", b: nums[1] ?? "", c: nums[2] ?? "", d: nums[3] ?? "" };
  const k = `m_${key}` as Key;
  return k in fa ? t(k, vars) : message;
}

export function useNum() {
  const lang = useLang((s) => s.lang);
  const fmt = new Intl.NumberFormat(lang === "fa" ? "fa-IR" : "en-US");
  return (n: number) => fmt.format(n);
}
